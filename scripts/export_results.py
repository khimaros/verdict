#!/usr/bin/env python3
"""export every verdict measurement as one machine-readable file.

the model registry (aimbot) is the dashboard: it reads this file as a
benchmark source of its own, beside the upstream jevbench board, and maps the
llama-swap model ids here onto its registry keys. so this file carries facts
and provenance, not presentation: which model, which suite, under which
settings, measured when and on what, with the path to the raw evidence.

usage:
  scripts/export_results.py             # write eval/results/export.json
  scripts/export_results.py --snapshot http://host:7860   # record weights first
"""

import argparse
import datetime
import glob
import json
import os
import re
import statistics
import subprocess
import sys
from pathlib import Path

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, ".."))
RESULTS = os.path.join(ROOT, "eval", "results")
OUT = os.path.join(RESULTS, "export.json")
# the README's model table is generated between these markers
README = os.path.join(ROOT, "README.md")
README_START = "<!-- models:start (generated by make export) -->"
README_END = "<!-- models:end -->"

SCHEMA = "verdict-export/1"
HARDWARE = "strix halo igpu, llama.cpp via llama-swap, reached over a ~150 ms vpn"
TIERS = ("easy", "original", "hard")
# weights read off each model's server after the fact, for runs whose server
# log predates logging them. valid only from SNAPSHOT_VALID_FROM: the llama-swap
# config for those models is known to be unchanged since then, and an older
# row gets no weights rather than a guess.
SNAPSHOT = os.path.join(RESULTS, "weights-snapshot.json")
SNAPSHOT_VALID_FROM = "2026-09-30T19:00:00+00:00"
# every key a suite's variant can carry, so one setting is always one key
DECISION_KEYS = ("layout", "order_averaging", "prior_correction", "long_lists")
VARIANT_KEYS = {"jevbench-public": DECISION_KEYS, "smoke": DECISION_KEYS,
                "option-mass": ("layout",), "agent": ("sweep",)}
METRICS_UNITS = {
    "accuracy": "share 0-1", "accuracy_easy": "share 0-1", "accuracy_original": "share 0-1",
    "accuracy_hard": "share 0-1", "hard_ece": "share 0-1",
    "hard_mean_confidence": "share 0-1", "option_mass": "share 0-1",
    "min_option_mass": "share 0-1", "correct": "count", "n": "count", "failures": "count",
    "runs": "count", "complete": "count", "reached_one": "count",
    "latency_p50_s": "seconds", "latency_p95_s": "seconds", "median_ms": "milliseconds",
    "usable": "boolean", "refusal": "text", "by_position": "count per position of 4",
    "statuses": "count per final status"}
# directories holding jevbench runs, one subdirectory per model (or per layout
# and then model). everything about the variant is read back from the run.
JEVBENCH_DIRS = ("jevbench", "jevbench-oa2", "jevbench-prior", "jevbench-layouts/*")

SUITES = {
    "jevbench-public": "jevbench's 231 public items (easy 48, original 72, hard 111) "
                       "through verdict's /v1/systemone with jevbench's own typesafe "
                       "adapter. public items only: the board's sealed items are not run.",
    "option-mass": "option mass on an unambiguous verification question at several "
                   "option counts; below the floor a formatter is refused.",
    "smoke": "element selection with ground truth: 16 cases, 4 option counts x 4 "
             "positions of the correct answer, fixed distractors.",
    "agent": "whole agent runs against a live site or device; complete means the "
             "task finished. confounded by the site and harness, see docs/EVALS.md.",
}


def rel(path):
    return os.path.relpath(path, ROOT)


def load(path):
    return json.loads(Path(path).read_text())


def mtime_utc(path):
    return datetime.datetime.fromtimestamp(os.path.getmtime(path), datetime.UTC).isoformat()


def git(*args):
    return subprocess.run(["git", *args], cwd=ROOT, capture_output=True, text=True,
                          check=False).stdout.strip()


def logged(server_log, field):
    """a value the server printed at startup, or None for an older log."""
    text = Path(server_log).read_text() if os.path.exists(server_log) else ""
    m = re.search(rf"^  {field} +(.+)$", text, re.M)
    return m.group(1).strip() if m else None


def provenance(row, server_log=None):
    """what was loaded and built, from the run's own log where it says, from the
    snapshot where the config is known unchanged, and nothing otherwise."""
    weights = logged(server_log, "weights") if server_log else None
    build = logged(server_log, "build") if server_log else None
    source = "server log" if weights else None
    snapshot = load(SNAPSHOT) if os.path.exists(SNAPSHOT) else {}
    if not weights and row["measured_utc"] >= SNAPSHOT_VALID_FROM and row["model"] in snapshot:
        weights, build = snapshot[row["model"]]["weights"], snapshot[row["model"]]["build"]
        source = f"snapshot, config unchanged since {SNAPSHOT_VALID_FROM}"
    elif weights:
        weights = json.loads(weights)
    row.update(weights=weights, llama_cpp_build=build, weights_source=source)
    row["variant"] = {k: row["variant"].get(k) for k in VARIANT_KEYS[row["suite"]]}
    return row


def ece(rows, bins=10):
    """top-label ece, equal-width bins, empty bins absent: jevbench's rule."""
    buckets = [[] for _ in range(bins)]
    for r in rows:
        conf = max(r["probs"].values())
        buckets[min(int(conf * bins), bins - 1)].append((conf, r["correct"]))
    return sum(len(b) / len(rows) * abs(statistics.mean(c for c, _ in b)
                                        - statistics.mean(k for _, k in b))
               for b in buckets if b)


def variant_of(server_log):
    """the settings a run was served with, as the server printed them."""
    text = Path(server_log).read_text() if os.path.exists(server_log) else ""
    layout = re.search(r"^  layout +(\S+)", text, re.M)
    averaging = re.search(r"order averaging (\d+)", text)
    return {"layout": layout.group(1) if layout else "chat",
            "order_averaging": int(averaging.group(1)) if averaging else 1,
            "prior_correction": "prior correction on" in text,
            "long_lists": long_lists(text)}


def long_lists(text):
    """how a list past the label ceiling is answered: `refuse` unless the
    server opted in to the exact wide alphabet or the approximate tournament.
    the wide alphabet wins when both are on, as the server does."""
    if "wide alphabet ON" in text:
        return "wide-alphabet"
    return "tournament" if "tournament ON" in text else "refuse"


def jevbench_row(run_dir):
    rows = [json.loads(line) for line in
            Path(run_dir, "results.jsonl").read_text().splitlines() if line]
    manifest = load(os.path.join(run_dir, "manifest.json"))
    answered = [r for r in rows if r["ok"] and r["probs"]]
    hard = [r for r in answered if r["task_id"].startswith("hard")]
    latency = sorted(r["latency_s"] for r in answered)
    metrics = {f"accuracy_{t}": round(statistics.mean(
        r["correct"] for r in rows if r["task_id"].startswith(t)), 4) for t in TIERS}
    metrics.update(
        accuracy=round(statistics.mean(r["correct"] for r in rows), 4),
        correct=sum(r["correct"] for r in rows), n=len(rows),
        failures=sum(not r["ok"] for r in rows),
        hard_ece=round(ece(hard), 4) if hard else None,
        hard_mean_confidence=round(statistics.mean(max(r["probs"].values()) for r in hard), 4)
        if hard else None,
        latency_p50_s=round(latency[len(latency) // 2], 3),
        latency_p95_s=round(latency[int(0.95 * len(latency))], 3))
    server_log = os.path.join(run_dir, "server.log")
    return provenance({"model": manifest["requested_model"], "suite": "jevbench-public",
                       "variant": variant_of(server_log),
                       "metrics": metrics, "measured_utc": manifest["finished_utc"],
                       "dataset_sha256": manifest["dataset_hash"], "path": rel(run_dir)},
                      server_log)


def jevbench_rows():
    for pattern in JEVBENCH_DIRS:
        for run in sorted(glob.glob(os.path.join(RESULTS, pattern, "*", "manifest.json"))):
            yield jevbench_row(os.path.dirname(run))


def option_mass_rows():
    for path in sorted(glob.glob(os.path.join(RESULTS, "option-mass-*.json"))
                       + glob.glob(os.path.join(RESULTS, "layouts", "mass-*.json"))):
        layout = re.search(r"mass-.+?-(chat|decider-plain|semif|winnow|standardone-native)"
                           r"\.json$|mass-deciders-(meta|chat)", path)
        for r in load(path):
            if "option_mass" not in r and "error" not in r:
                continue
            yield provenance({
                "model": r["model"], "suite": "option-mass",
                "variant": {"layout": _layout_name(layout)},
                "metrics": {"option_mass": r.get("option_mass"),
                            "usable": r.get("usable", False), "refusal": r.get("error"),
                            # correct is "k/n" over the verification counts
                            "n": int(r["correct"].split("/")[1]) if r.get("correct") else None},
                "measured_utc": mtime_utc(path), "measured_utc_source": "file mtime",
                "path": rel(path)})


def _layout_name(match):
    if not match:
        return "chat"
    name = match.group(1) or match.group(2)
    return "registry" if name == "meta" else name


def smoke_rows():
    for path in sorted(glob.glob(os.path.join(RESULTS, "smoke-models*.json"))):
        for r in load(path):
            correct, n = (int(x) for x in r["correct"].split("/"))
            # smoke_models.py scores with the tournament enabled and records the
            # debiasing it was run with
            yield provenance({
                "model": r["model"], "suite": "smoke",
                "variant": {"layout": "chat", "order_averaging": r.get("order_averaging", 1),
                            "prior_correction": False,
                            "long_lists": "wide-alphabet" if r.get("wide_alphabet")
                            else "tournament"},
                "metrics": {"accuracy": r["accuracy"], "correct": correct, "n": n,
                            "min_option_mass": r["min_option_mass"],
                            "median_ms": r["median_ms"], "by_position": r["by_position"]},
                "measured_utc": mtime_utc(path), "measured_utc_source": "file mtime",
                "path": rel(path)})


# scripts/eval_interventions.py names its arms; the settings each one means
INTERVENTIONS = {"baseline": (1, False), "order-averaged": (2, False),
                 "prior-corrected": (1, True), "both": (2, True)}


def intervention_rows():
    """the debiasing arms of the element-selection benchmark, one row each."""
    for path in sorted(glob.glob(os.path.join(RESULTS, "interventions-*.json"))):
        d = load(path)
        for s in d["summaries"]:
            averaging, prior = INTERVENTIONS[s["intervention"]]
            correct, n = (int(x) for x in s["correct"].split("/"))
            yield provenance({
                "model": d["model"], "suite": "smoke",
                # the arms were scored without opting in to either long-list mode
                "variant": {"layout": "chat", "order_averaging": averaging,
                            "prior_correction": prior, "long_lists": "refuse"},
                "metrics": {"accuracy": s["accuracy"], "correct": correct, "n": n,
                            "min_option_mass": s["min_option_mass"],
                            "median_ms": None, "by_position": s["by_position"]},
                "measured_utc": mtime_utc(path), "measured_utc_source": "file mtime",
                "path": rel(path)})


def agent_rows():
    for path in sorted(glob.glob(os.path.join(RESULTS, "sweep-*", "summary.json"))):
        sweep = os.path.basename(os.path.dirname(path))
        for model, r in load(path).items():
            yield provenance({
                "model": model, "suite": "agent", "variant": {"sweep": sweep},
                "metrics": {"runs": r["runs"], "n": r["runs"], "complete": r["complete"],
                            "reached_one": r["reached_one"], "statuses": r["statuses"]},
                "measured_utc": mtime_utc(path), "measured_utc_source": "file mtime",
                "path": rel(path)})


def snapshot(base_url, models):
    """ask each model's server what it loaded. this swaps every model on the
    backend in turn, which is why it is a separate, explicit step."""
    sys.path.insert(0, os.path.join(ROOT, "python"))
    from llama_verdict.backend import HttpBackend, weights_from_props

    out = {}
    for model in sorted(models):
        try:
            props = HttpBackend(base_url, model).props()
        except OSError as e:
            print(f"  {model}: {e}")
            continue
        out[model] = {"weights": weights_from_props(props), "build": props.get("build_info"),
                      "read_utc": datetime.datetime.now(datetime.UTC).isoformat()}
        print(f"  {model}: {out[model]['weights']}")
    Path(SNAPSHOT).write_text(json.dumps(out, indent=1, sort_keys=True) + "\n")
    print(f"wrote {len(out)} models to {rel(SNAPSHOT)}")


def all_rows():
    return [*jevbench_rows(), *option_mass_rows(), *smoke_rows(), *intervention_rows(),
            *agent_rows()]


def default_jevbench(rows):
    """one jevbench row per model: its own layout where it has one, else chat,
    with no debiasing, which is how the model is served unless asked."""
    best = {}
    for r in rows:
        v = r["variant"]
        if (r["suite"] != "jevbench-public" or v["order_averaging"] != 1
                or v["prior_correction"] or v["long_lists"] != "refuse"):
            continue
        rank = (v["layout"] != "chat", r["measured_utc"])
        if r["model"] not in best or rank > best[r["model"]][0]:
            best[r["model"]] = (rank, r)
    return sorted((r for _, r in best.values()), key=lambda r: -r["metrics"]["accuracy"])


# the README's score columns, and whether a higher value is the better one
README_COLUMNS = (("accuracy", True), ("accuracy_hard", True), ("hard_ece", False),
                  ("latency_p50_s", False))


def readme_table(rows):
    """the default reading of every model, the best value in each column bold,
    every model that ties for it included."""
    table = default_jevbench(rows)
    best = {key: (max if higher else min)(r["metrics"][key] for r in table)
            for key, higher in README_COLUMNS}

    def cell(m, key, text):
        return f"**{text}**" if m[key] == best[key] else text

    lines = ["| model | read as | jevbench public | hard tier | hard ece | p50 latency |",
             "|---|---|---|---|---|---|"]
    for r in table:
        m = r["metrics"]
        lines.append(" | ".join((
            f"| {r['model']}", r["variant"]["layout"],
            cell(m, "accuracy", f"{m['correct']}/{m['n']} ({m['accuracy']:.3f})"),
            cell(m, "accuracy_hard", f"{m['accuracy_hard']:.3f}"),
            cell(m, "hard_ece", f"{m['hard_ece']:.3f}"),
            cell(m, "latency_p50_s", f"{m['latency_p50_s']:.2f} s"))) + " |")
    return "\n".join(lines)


def update_readme(rows):
    """rewrite the generated table between README's markers, and nothing else."""
    readme = Path(README)
    text = readme.read_text()
    start, end = text.index(README_START) + len(README_START), text.index(README_END)
    readme.write_text(text[:start] + "\n" + readme_table(rows) + "\n" + text[end:])


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--snapshot", metavar="BASE_URL",
                    help="first record which weights each exported model's server "
                         "loads, for runs whose logs predate recording it")
    args = ap.parse_args()
    if args.snapshot:
        snapshot(args.snapshot, {r["model"] for r in all_rows()
                                 if r["measured_utc"] >= SNAPSHOT_VALID_FROM})
    rows = all_rows()
    export = {"schema": SCHEMA, "source": "verdict", "hardware": HARDWARE,
              "verdict_rev": git("rev-parse", "HEAD"),
              "verdict_dirty": bool(git("status", "--porcelain")),
              "metrics_units": METRICS_UNITS, "suites": SUITES, "rows": rows}
    Path(OUT).write_text(json.dumps(export, indent=1, sort_keys=True) + "\n")
    update_readme(rows)
    print(f"wrote {len(rows)} rows to {rel(OUT)} and the table in {rel(README)}")


if __name__ == "__main__":
    main()
